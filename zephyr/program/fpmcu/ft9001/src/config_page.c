struct ft_config_page {
	/* 0x00 - 0x04; 0x3AEC3721 for valid code */
	uint32_t code_valid_control_word;
	uint8_t reserved_04_18[0x14];
	/* 0x18 - 0x1C; 0x904E3C21 for valid code */
	uint32_t config_page_verification_enable;
	uint8_t reserved_1C_20[0x4];
	/* 0x20 - 0x24 */
	uint32_t code_start_address;
	/* 0x24 - 0x28 */
	uint32_t code_length;
	uint8_t reserved_28_40[0x18];
	/* 0x40 - 0x140 */
	uint8_t code_sig[256]; /* RSA2048 code signature */
	/* 0x140 - 0x160 */
	uint8_t config_page_hash[32]; /* SHA256 of the config page */
	/* 0x160 - 0x190 */
	uint8_t spi_flash_param[0x30];
	uint8_t reserved_190_1F4[0x64];
	/* 0x1F4 - 0x1F8; 0x301821EF for OTP */
	uint32_t config_page_location;
	uint8_t reserved_1F8_200[0x8];
} __packed;

